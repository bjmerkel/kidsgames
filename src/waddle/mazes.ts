const COLS = 15;
const ROWS = 19;

function maze(rows: string[]): string[] {
  if (rows.length !== ROWS) throw new Error(`maze rows ${rows.length}`);
  for (const row of rows) {
    if (row.length !== COLS) throw new Error(`maze width ${row.length}: ${row}`);
  }
  return rows;
}

